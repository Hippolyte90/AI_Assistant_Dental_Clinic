"""Build data/catalog.json from the xlsx and fill catalog ids in the expected plans."""

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.config import CATALOG_PATH, DATA_DIR, PRICE_LIST_PATH
from app.services.catalog import parse_price_list, save_catalog


def write_report(items: list) -> None:
    """Write the list of source-data anomalies; prices are never changed."""
    codes, names = defaultdict(list), defaultdict(list)
    for item in items:
        if item.code:
            codes[item.code].append(item)
        names[item.name].append(item)
    lines = [
        "# Catalog data-quality report",
        "",
        "Generated by `build_catalog.py`.",
        "",
    ]
    lines += [
        f"- Services: {len(items)}",
        f"- Without a code: {sum(not i.code for i in items)}",
    ]
    lines += ["", "## Duplicate codes", ""]
    for code, group in codes.items():
        if len(group) > 1:
            detail = "; ".join(f"{i.id} {i.name} = {i.price_eur}" for i in group)
            lines.append(f"- `{code}`: {detail}")
    lines += ["", "## Same name in several sections", ""]
    for name, group in names.items():
        if len(group) > 1:
            prices = ", ".join(f"{i.id} = {i.price_eur}" for i in group)
            flag = " **(prices differ)**" if len({i.price_eur for i in group}) > 1 else ""
            lines.append(f"- {name}: {prices}{flag}")
    (DATA_DIR / "catalog_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def fill_expected(items: list) -> None:
    """Add catalog ids to the hand-written expected plans."""
    index = {(i.section, i.name): i.id for i in items}
    for path in sorted((DATA_DIR / "sample_notes").glob("*.expected.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for row in data["items"]:
            row["catalog_id"] = index[(row["section"], row["name"])]
        path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    catalog_items = parse_price_list(PRICE_LIST_PATH)
    save_catalog(catalog_items, CATALOG_PATH)
    write_report(catalog_items)
    fill_expected(catalog_items)
    print(f"{len(catalog_items)} services written to {CATALOG_PATH}")
